def _clean_text(value: Any, limit: int) -> str:
	text = str(value or "").replace("\r\n", "\n").strip()
	return text if len(text) <= limit else ""


def validate_generated(raw: Mapping[str, Any], slot: Slot | None, section: SectionPlan) -> dict[str, Any] | None:
	"""A cleaned question dict, or None when it can't be used as is."""
	question_type = str(raw.get("type") or (slot.question_type if slot else "")).strip().casefold()
	if question_type not in QUESTION_TYPES:
		return None
	prompt = _clean_text(raw.get("prompt"), _MAX_PROMPT)
	code = _clean_text(raw.get("code"), _MAX_CODE).strip("\n")
	if not prompt or code.count("\n") > 40:
		return None
	if question_type in {CODE_OUTPUT, FIND_BUG, PSEUDOCODE} and not code:
		return None
	if code and code.count("\n") < 2 and len(code) > 100:
		return None  # squashed onto one line: unreadable on screen
	options = [str(o).strip() for o in (raw.get("options") or []) if str(o or "").strip()]
	expected = 5 if question_type == MCQ_MULTI else 4
	if len(options) not in {4, 5} or len(options) < expected - (1 if question_type == MCQ_MULTI else 0):
		return None
	if len({o.casefold() for o in options}) != len(options):
		return None
	try:
		correct = sorted({int(i) for i in (raw.get("correct") or [])})
	except (TypeError, ValueError):
		return None
	if not correct or any(i < 0 or i >= len(options) for i in correct):
		return None
	if question_type == MCQ_MULTI:
		if not 2 <= len(correct) <= 3:
			return None
		if "select all" not in prompt.casefold():
			prompt = f"{prompt} (Select all that apply)"
	elif len(correct) != 1:
		return None
	if question_type in {"mcq_single", "scenario"} and all(parse_number(o) is not None for o in options):
		question_type = NUMERICAL  # a calculation in disguise: check it like one
	language = str(raw.get("language") or section.language or "").strip().casefold()
	if question_type == PSEUDOCODE:
		language = "pseudocode"
	difficulty = str(raw.get("difficulty") or (slot.difficulty if slot else "medium")).casefold()
	return {
		"type": question_type,
		"difficulty": difficulty if difficulty in {"easy", "medium", "hard"} else "medium",
		"topic": _clean_text(raw.get("topic") or (slot.topic if slot else ""), 80) or section.title,
		"prompt": prompt,
		"code": code,
		"language": language if code else "",
		"options": options,
		"correct": correct,
		"explanation": _clean_text(raw.get("explanation"), 600),
		"verify_expression": _clean_text(raw.get("verify_expression"), 300),
		"verify_python": _clean_text(raw.get("verify_python"), _MAX_CODE),
	}


def first_json_object(raw: str) -> dict[str, Any]:
	"""The first complete JSON object in a reply, ignoring anything before or
	after it (a second object, a sentence, a code fence)."""
	text = str(raw or "")
	decoder = json.JSONDecoder()
	start = text.find("{")
	while start != -1:
		try:
			value, _ = decoder.raw_decode(text, start)
		except json.JSONDecodeError:
			start = text.find("{", start + 1)
			continue
		if isinstance(value, dict):
			return value
		start = text.find("{", start + 1)
	raise ValueError("no JSON object in the reply")


def question_hash(prompt: str, code: str) -> str:
	key = re.sub(r"\s+", " ", f"{prompt}\n{code}".casefold()).strip()
	return hashlib.sha256(key.encode("utf-8")).hexdigest()[:20]



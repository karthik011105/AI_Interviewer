def _about_other_language(text: str, language: str) -> bool:
	lowered = f" {text.casefold()} "
	return any(
		key != language and any(word in lowered for word in words)
		for key, words in _LANGUAGE_WORDS.items()
	)
_FENCE = re.compile(r"```[a-zA-Z0-9+#]*\n?(.*?)```", re.DOTALL)


def _bank_candidates(blueprint: OABlueprint) -> dict[str, list[dict[str, Any]]]:
	"""Curated bank questions by section, cleaned for display."""
	from backend.assessment.question_bank import load_question_bank

	families = set(_FAMILY_TO_BANK.get(blueprint.family, ()))
	by_section: dict[str, list[dict[str, Any]]] = {}
	for q in load_question_bank():
		if not q.active or not families.intersection(q.role_families):
			continue
		prompt, code = q.prompt, ""
		fence = _FENCE.search(q.prompt)
		if fence:
			code = fence.group(1).strip("\n")
			prompt = _FENCE.sub("", q.prompt).strip()
			if code.count("\n") < 1 or "return ;" in code:
				continue  # code that lost its line breaks or JSX in the bank import
		if blueprint.family == "software" and _about_other_language(f"{prompt} {code}", blueprint.language):
			continue
		options = [o.text for o in q.options]
		correct = [i for i, o in enumerate(q.options) if o.id == q.correct_option_id]
		if len(correct) != 1 or not prompt:
			continue
		if q.question_type == "code_output" or code:
			section = "code"
		elif q.topic in _BANK_FUNDAMENTALS:
			section = "fundamentals"
		else:
			section = "technical"
		by_section.setdefault(section, []).append({
			"type": CODE_OUTPUT if q.question_type == "code_output" else "mcq_single",
			"difficulty": q.difficulty, "topic": q.topic.replace("_", " "), "prompt": prompt, "code": code,
			"language": "", "options": options, "correct": correct, "explanation": q.explanation,
			"verified": "curated", "source": "bank",
		})
	return by_section



_SECTION_PROMPT = """You write questions for a timed online assessment (OA) that companies use to screen freshers for a {role_title} role. Pitch it at TCS NQT Advanced, Infosys Specialist Programmer, Accenture and product-company OA level (Amazon, Microsoft) - not a beginner quiz.

Section: {section_title}
Write exactly {count} questions, one per slot, in this order:
{slot_lines}

Rules for every question:
- Medium and hard questions must need multi-step reasoning, an edge case or a common misconception. No one-line definitions and no trivia (versions, dates, who created what).
- 4 options (5 for mcq_multi). Distractors are plausible answers a candidate gets by making a typical mistake, in the same style and length as the correct one. No "All of the above" or "None of the above".
- Code, pseudocode or a data table goes in "code", never inside "prompt". Write code the way it appears in an editor: one statement per line with normal indentation, line breaks escaped as \\n in the JSON string - never squashed onto one line.
- "explanation": one or two sentences on why the answer is right.

Per type:
- mcq_single / scenario: exactly one correct option. A scenario is a short realistic work situation asking for the best action or the likely cause.
- mcq_multi: 2 or 3 correct options out of 5; end the prompt with "(Select all that apply)".
- numerical: each option is a single number with an optional unit ("2.5 hours", "37.5%"). "verify_expression" computes the correct option's number from the problem's own numbers - plain arithmetic only, no variables, no equations, no units - e.g. "(6/0.5 + 4/0.75) / 2" or "comb(8, 3) * 2". Allowed: + - * / ** // % ( ) comb perm factorial sqrt log round.
- code_output: a complete runnable {language_hint} program, 6 to 16 lines, standard library only, deterministic output; ask what it prints; options are possible exact outputs.
- find_bug: a 6 to 14 line {language_hint} snippet with exactly one real bug; options describe candidate bugs or name the faulty line.
- pseudocode: Infosys/Accenture-style pseudocode (integer variables, loops, if/else, functions) asking what is printed; also give "verify_python", an equivalent Python 3 program that prints exactly the correct answer.

Return JSON only:
{{"questions": [{{"slot": 1, "type": "...", "difficulty": "...", "topic": "...", "prompt": "...", "code": "", "language": "", "options": ["...", "..."], "correct": [0], "explanation": "...", "verify_expression": "", "verify_python": ""}}]}}
"correct" holds 0-based indexes into "options"."""



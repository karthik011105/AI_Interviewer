def _models() -> tuple[str, str]:
	import os

	return (
		os.getenv("GROQ_ASSESSMENT_MODEL") or "openai/gpt-oss-120b",
		os.getenv("GROQ_ASSESSMENT_ALT_MODEL") or "openai/gpt-oss-20b",
	)


def _model_for(section_key: str, language: str = "") -> str:
	"""The stronger model writes everything Judge0 can't prove: aptitude (the
	smaller one wrote equations instead of formulas and mis-keyed often),
	fundamentals, technical, and code in a language that won't run here
	(Java, under Docker Desktop). The smaller model writes runnable code, and
	its own per-minute token budget keeps the two from queueing on each other."""
	main, alt = _models()
	if section_key == "code" and language in RUNNABLE_HERE:
		return alt
	return main


def _checker_for(section_key: str, language: str = "") -> str:
	"""The other model gives the second opinion, so a model's blind spot
	isn't checked by itself."""
	main, alt = _models()
	return alt if _model_for(section_key, language) == main else main


# Languages Judge0 runs in this setup. Java's VM can't start under the
# per-process memory limit Docker Desktop needs (see oa_verify).
RUNNABLE_HERE = frozenset({"python", "cpp", "c", "javascript", "bash"})


def _pick(candidates: list[dict[str, Any]], count: int, rng: random.Random) -> list[dict[str, Any]]:
	"""Prefer checked questions, keep a spread of difficulty."""
	rank = {VERIFIED: 0, CROSS_CHECKED: 1, "curated": 2}
	rng.shuffle(candidates)
	candidates.sort(key=lambda q: rank.get(str(q.get("verified")), 2))
	return candidates[:count]


class OABuild:
	"""One attempt, built section by section in test order.

	A full checked attempt costs ~20k tokens, and the free tier allows ~8k a
	minute per model, so building it all up front took 50-90 s. Real OAs are
	sectioned anyway: the candidate starts on the first section as soon as it
	is ready, and each later section is appended while they work (``attach``).
	"""

	def __init__(
		self,
		*,
		role_key: str,
		role_title: str = "",
		total_questions: int | None = None,
		generate: Callable[[str, str], str] | None = None,
		solve: Callable[[str, str], str] | None = None,
		run: Callable[[str, str], Mapping[str, Any]] | None = None,
		use_pool: bool = True,
		rng: random.Random | None = None,
	) -> None:
		from backend.nlp.question_generator import _resolve_role_topics

		self.role_key = role_key
		self.rng = rng or random.Random()
		self.solve = solve or (generate if generate else _default_solve)
		self.generate = generate or _default_generate
		self.run_code = run if run is not None else _default_run
		self.use_pool = use_pool
		role_topics = tuple(_resolve_role_topics(role_key, role_title, [], []))
		self.blueprint = build_oa_blueprint(
			role_key, role_title, role_topics=role_topics, total_questions=total_questions, rng=self.rng
		)
		self.build_id = uuid.uuid4().hex
		self.lock = threading.RLock()
		self.questions: list[dict[str, Any]] = []  # snapshot items, in test order
		self.sections_done = 0
		self.done = False
		self.failed = False
		self._first_ready = threading.Event()
		self._finished = threading.Event()
		self._on_append: Callable[[list[dict[str, Any]], dict[str, Any]], None] | None = None
		self._seen: set[str] = set()
		self._bank: dict[str, list[dict[str, Any]]] | None = None

	# -- building ------------------------------------------------------------

	def run(self) -> "OABuild":
		started = time.monotonic()
		try:
			for index, section in enumerate(self.blueprint.sections):
				_RATE_LIMIT_WAIT.seconds = 20.0 if index == 0 else 45.0
				chosen = self._build_section(section)
				items = [_snapshot_item(q, self.rng) for q in chosen]
				with self.lock:
					self.questions.extend(items)
					self.sections_done += 1
					if self.sections_done == len(self.blueprint.sections):
						self.done = True
					self._notify(items)
				self._first_ready.set()
		except Exception:
			_LOGGER.exception("OA build for %s failed.", self.role_key)
			with self.lock:
				self.failed = self.done = True
				self._notify([])
		finally:
			self._first_ready.set()
			self._finished.set()
			sources: dict[str, int] = {}
			for q in self.questions:
				sources[q["selection_source"]] = sources.get(q["selection_source"], 0) + 1
			_LOGGER.info(
				"OA batch for %s: %d of %d questions %s in %.1fs.",
				self.role_key, len(self.questions), self.blueprint.total_questions, sources, time.monotonic() - started,
			)
		return self

	def _build_section(self, section: SectionPlan) -> list[OAQuestion]:
		blueprint, rng = self.blueprint, self.rng
		language = section.language or blueprint.language
		model, checker = _model_for(section.key, language), _checker_for(section.key, language)

		reused: list[dict[str, Any]] = []
		if self.use_pool:
			# Ask for plenty to see how deep the pool is, then keep a share:
			# more reuse means fewer tokens and a faster start, but never so
			# much that two attempts look alike.
			sample = _sample_pool(blueprint.family, section.key, section.count * POOL_DEEP_FACTOR)
			share = POOL_REUSE_SHARE_FULL if len(sample) >= section.count * POOL_DEEP_FACTOR else POOL_REUSE_SHARE
			reused = [{**doc, "source": "pool"} for doc in sample[: int(section.count * share)]]

		def _fresh(count: int, first_round: bool) -> list[dict[str, Any]]:
			if count <= 0:
				return []
			spare = max(1, round(count * (SPARE_SHARE.get(section.key, DEFAULT_SPARE_SHARE) if first_round else DEFAULT_SPARE_SHARE)))
			slots = (section.slots[:count] if first_round else []) + make_slots(section.spec, spare if first_round else count + spare, rng)
			made = generate_section(section, blueprint, slots, model=model, generate=self.generate)
			return cross_check(check_all(made, self.run_code), model=checker, generate=self.solve)

		fresh = _fresh(section.count - len(reused), first_round=True)
		# The checks drop questions by design. One more round if the section
		# is short, before falling back to the (easier) curated bank.
		short = section.count - len(reused) - len(fresh)
		if short > 0:
			fresh += _fresh(short, first_round=False)
		if self.use_pool:
			_save_to_pool(_pool_docs(blueprint.family, section, fresh))

		chosen: list[OAQuestion] = []
		self._take([*reused, *({**q, "source": "generated"} for q in fresh)], section, chosen)
		if len(chosen) < section.count:
			if self._bank is None:
				self._bank = _bank_candidates(blueprint)
			# The section's own bank questions first, then any bank question.
			self._take(self._bank.get(section.key, []), section, chosen)
			if len(chosen) < section.count:
				others = [{**q, "section": key} for key, qs in self._bank.items() if key != section.key for q in qs]
				self._take(others, section, chosen)
		return chosen

	def _take(self, questions: Sequence[dict[str, Any]], section: SectionPlan, chosen: list[OAQuestion]) -> None:
		titles = {s.key: s.title for s in self.blueprint.sections}
		unique: dict[str, dict[str, Any]] = {}
		for q in questions:
			digest = question_hash(q["prompt"], q["code"])
			if digest not in self._seen and digest not in unique:
				unique[digest] = q
		for q in _pick(list(unique.values()), section.count - len(chosen), self.rng):
			digest = question_hash(q["prompt"], q["code"])
			self._seen.add(digest)
			# A bank stand-in keeps its own section label: a Java question
			# filling an aptitude gap is still a Java question.
			key = q.get("section") or section.key
			chosen.append(OAQuestion(
				question_id=f"oa-{digest}", section=key, section_title=titles.get(key, "Technical"),
				question_type=q["type"], difficulty=q["difficulty"], topic=q["topic"], prompt=q["prompt"],
				code=q["code"], code_language=q.get("language") or "", options=list(q["options"]),
				correct=list(q["correct"]), explanation=q.get("explanation") or "",
				verified=str(q.get("verified") or "unverified"), source=q.get("source") or "generated",
			))

	# -- handing over ----------------------------------------------------------

	def wait_first_section(self, timeout: float) -> bool:
		return self._first_ready.wait(timeout) and bool(self.questions)

	def wait_finished(self, timeout: float | None = None) -> bool:
		return self._finished.wait(timeout)

	def planned_total(self) -> int:
		"""The size the candidate is told: the plan until the last section is
		in, then what was actually built."""
		return len(self.questions) if self.done else self.blueprint.total_questions

	def meta(self) -> dict[str, Any]:
		with self.lock:
			counts: dict[str, int] = {}
			for q in self.questions:
				counts[q["section"]] = counts.get(q["section"], 0) + 1
			return {
				"pending": not self.done,
				"sections": [
					{"key": s.key, "title": s.title, "count": counts.get(s.key, 0) if self.done else max(counts.get(s.key, 0), s.count)}
					for s in self.blueprint.sections
				],
				"total_questions": self.planned_total(),
			}

	def snapshot(self) -> dict[str, Any]:
		with self.lock:
			return {
				"format": "oa",
				"build_id": self.build_id,
				"family": self.blueprint.family,
				"role_families": [self.blueprint.family],
				"domains": [],
				**{k: v for k, v in self.meta().items() if k != "total_questions"},
				"questions": list(self.questions),
			}

	def attach(self, on_append: Callable[[list[dict[str, Any]], dict[str, Any]], None]) -> None:
		"""Send every later section to ``on_append(new_items, meta)``. Call while
		holding ``lock`` together with ``snapshot`` so nothing falls between."""
		self._on_append = on_append

	def _notify(self, items: list[dict[str, Any]]) -> None:
		if self._on_append is None:
			return
		try:
			self._on_append(items, self.meta())
		except Exception:
			_LOGGER.warning("Could not append an OA section to the stored attempt.", exc_info=True)


def build_oa_batch(**kwargs: Any) -> dict[str, Any]:
	"""One complete OA attempt, built synchronously (tests, scripts)."""
	return OABuild(**kwargs).run().snapshot()


def _snapshot_item(q: OAQuestion, rng: random.Random) -> dict[str, Any]:
	order = list(range(len(q.options)))
	rng.shuffle(order)
	ids = _OPTION_IDS[: len(order)]
	options = [{"id": ids[new], "text": q.options[old]} for new, old in enumerate(order)]
	id_of = {old: ids[new] for new, old in enumerate(order)}
	correct_ids = sorted(id_of[i] for i in q.correct)
	return {
		"question_id": q.question_id,
		"section": q.section,
		"section_title": q.section_title,
		"prompt": q.prompt,
		"code": q.code,
		"code_language": q.code_language,
		"question_type": q.question_type,
		"multi_select": q.question_type == MCQ_MULTI,
		"topic": q.topic,
		"difficulty": q.difficulty,
		"skill_tag": q.topic,
		"options": options,
		"correct_option_id": correct_ids[0],
		"correct_option_ids": correct_ids,
		"explanation": q.explanation,
		"verified": q.verified,
		"selection_source": q.source,
		"is_core": False,
	}


def section_results(record: Mapping[str, Any]) -> list[dict[str, Any]]:
	"""Correct / answered / total per OA section, in test order."""
	batch = record.get("batch_json") if isinstance(record.get("batch_json"), Mapping) else {}
	state = record.get("state_json") if isinstance(record.get("state_json"), Mapping) else {}
	answers = state.get("answers") if isinstance(state.get("answers"), Mapping) else {}
	results: dict[str, dict[str, Any]] = {}
	for question in batch.get("questions") or []:
		if not isinstance(question, Mapping):
			continue
		title = str(question.get("section_title") or "Questions")
		entry = results.setdefault(title, {"title": title, "correct": 0, "answered": 0, "total": 0})
		entry["total"] += 1
		answer = answers.get(str(question.get("question_id") or ""))
		if isinstance(answer, Mapping):
			entry["answered"] += 1
			entry["correct"] += 1 if answer.get("is_correct") else 0
	return list(results.values())



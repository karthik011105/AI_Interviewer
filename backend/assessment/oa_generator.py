"""Build one online-assessment attempt: generate, check, top up, shuffle.

1. ``oa_blueprint`` decides the size (15-25), sections and slots.
2. Each section is generated by Groq in parallel - one call per section,
   asking for a few spare questions on top of its slots.
3. Every question is validated (shape) and checked where it can be
   (``oa_verify``: code run on Judge0, numerical answers recomputed). Wrong
   keys are corrected or the question is dropped.
4. Verified questions are saved to a shared pool and later attempts reuse a
   share of it, so Groq usage falls as the pool grows.
5. Any shortfall is filled from the curated question bank.

Generation takes several seconds, so it starts in the background when the
candidate picks a role (``prefetch``); /assessment/start then usually finds
the attempt ready.
"""


_PREFETCH_LOCK = threading.Lock()
_PREFETCH: dict[str, tuple[str, int, OABuild | None]] = {}
_BUILD_EXECUTOR = ThreadPoolExecutor(max_workers=4, thread_name_prefix="oa-build")
_PREFETCH_DELAY_SECONDS = 2.0  # the candidate may click through a few roles


def _prefetch_enabled() -> bool:
	import os

	if os.getenv("DISABLE_OA_PREFETCH", "").strip().lower() in {"1", "true", "yes"}:
		return False
	try:
		from backend.config import get_settings

		return get_settings().groq is not None
	except Exception:
		return False


def prefetch(session_id: str, role_key: str, role_title: str = "") -> None:
	"""Start preparing this session's attempt in the background. Skipped in
	test runs and when Groq isn't configured (nothing to generate with)."""
	if not session_id or not role_key or not _prefetch_enabled():
		return
	with _PREFETCH_LOCK:
		generation = (_PREFETCH.get(session_id, ("", 0, None))[1] or 0) + 1
		_PREFETCH[session_id] = (role_key, generation, None)

	def _job() -> None:
		time.sleep(_PREFETCH_DELAY_SECONDS)
		with _PREFETCH_LOCK:
			current = _PREFETCH.get(session_id)
			if not current or current[1] != generation:
				return  # a newer role choice replaced this one
			build = OABuild(role_key=role_key, role_title=role_title)
			_PREFETCH[session_id] = (role_key, generation, build)
		build.run()

	_BUILD_EXECUTOR.submit(_job)


def take_build(session_id: str, role_key: str, *, wait_seconds: float = 10.0) -> OABuild | None:
	"""The background build for this session and role, if one was started.
	Waits briefly if the prefetch is still in its start-up delay."""
	deadline = time.monotonic() + wait_seconds
	while True:
		with _PREFETCH_LOCK:
			entry = _PREFETCH.get(session_id)
			if not entry or entry[0] != role_key:
				return None
			if entry[2] is not None:
				_PREFETCH.pop(session_id, None)
				return None if entry[2].failed else entry[2]
		if time.monotonic() >= deadline:
			return None
		time.sleep(0.25)


def start_build(*, role_key: str, role_title: str = "", total_questions: int | None = None) -> OABuild:
	"""Start building an attempt now (no prefetch, or a "New test")."""
	build = OABuild(role_key=role_key, role_title=role_title, total_questions=total_questions)
	_BUILD_EXECUTOR.submit(build.run)
	return build



def _pool_docs(family: str, section: SectionPlan, questions: Sequence[dict[str, Any]]) -> list[dict[str, Any]]:
	docs = []
	for q in questions:
		if q.get("verified") not in {VERIFIED, CROSS_CHECKED}:
			continue  # only questions that passed a check are shared
		docs.append({
			"_id": question_hash(q["prompt"], q["code"]),
			"family": family,
			"section": section.key,
			"section_title": section.title,
			**{k: q[k] for k in ("type", "difficulty", "topic", "prompt", "code", "language", "options", "correct", "explanation", "verified")},
		})
	return docs


def _save_to_pool(docs: Sequence[dict[str, Any]]) -> None:
	if not docs:
		return
	try:
		from backend.database.queries import save_oa_questions

		save_oa_questions(list(docs))
	except Exception:
		_LOGGER.warning("Could not save OA questions to the shared pool.", exc_info=True)


def _sample_pool(family: str, section_key: str, limit: int) -> list[dict[str, Any]]:
	if limit <= 0:
		return []
	try:
		from backend.database.queries import sample_oa_questions

		return list(sample_oa_questions(family, section_key, limit))
	except Exception:
		_LOGGER.info("OA question pool unavailable; generating everything fresh.", exc_info=True)
		return []



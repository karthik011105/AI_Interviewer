def _slot_lines(slots: Sequence[Slot], language: str) -> str:
	lines = []
	for index, slot in enumerate(slots, start=1):
		extra = f", language={language}" if slot.question_type in {CODE_OUTPUT, FIND_BUG} and language else ""
		lines.append(f"{index}. type={slot.question_type}, difficulty={slot.difficulty}, topic={slot.topic}{extra}")
	return "\n".join(lines)


# How long to wait when Groq's per-minute budget is used up. The first
# section is what the candidate is waiting for, so it falls back to the bank
# sooner; later sections are written while they answer and can wait longer.
_RATE_LIMIT_WAIT = threading.local()


def _max_rate_limit_wait() -> float:
	return getattr(_RATE_LIMIT_WAIT, "seconds", 20.0)


def _complete(prompt: str, model: str, *, temperature: float, reasoning: str) -> str:
	from backend.config import get_settings
	from backend.nlp.groq_client import create_chat_completion

	settings = get_settings().groq
	if settings is None:
		raise RuntimeError("Groq is not configured.")
	result = create_chat_completion(
		settings=settings,
		model=model,
		temperature=temperature,
		messages=[{"role": "user", "content": prompt}],
		# No response_format: Groq's JSON mode with gpt-oss reasoning failed
		# with json_validate_failed and an empty generation, ~8 s per retry
		# (34 s for one section). The prompt asks for JSON and
		# first_json_object() reads it.
		extra_body={"reasoning_effort": reasoning} if model.startswith("openai/gpt-oss") else None,
		timeout=90,
		max_rate_limit_wait=_max_rate_limit_wait(),
	)
	usage = getattr(result, "usage", None)
	if usage is not None:
		_LOGGER.info(
			"OA %s call on %s: %s prompt + %s completion tokens.",
			"check" if temperature < 0.5 else "generate", model,
			getattr(usage, "prompt_tokens", "?"), getattr(usage, "completion_tokens", "?"),
		)
	return str(result.choices[0].message.content or "")


def _default_generate(prompt: str, model: str) -> str:
	# Writing: varied (high temperature) and quick - gpt-oss reasons before
	# answering, and "low" keeps it inside the free tier's per-minute budget.
	# Calculation sections think harder: with "low", most aptitude and maths
	# questions failed the key-vs-formula check (e.g. 3, 8, 24, 72, ?).
	careful = "Section: Aptitude" in prompt or "Section: Maths" in prompt or "Section: Statistics" in prompt
	return _complete(prompt, model, temperature=0.8, reasoning="medium" if careful else "low")


def _default_solve(prompt: str, model: str) -> str:
	# Second opinion: deterministic and careful. In testing a quick checker
	# got a three-consecutive-integers question wrong and dropped it.
	return _complete(prompt, model, temperature=0.1, reasoning="medium")


def generate_section(
	section: SectionPlan,
	blueprint: OABlueprint,
	slots: Sequence[Slot],
	*,
	model: str,
	generate: Callable[[str, str], str],
) -> list[dict[str, Any]]:
	"""Valid (not yet checked) questions for one section's slots."""
	if not slots:
		return []
	language = section.language or blueprint.language
	prompt = _SECTION_PROMPT.format(
		role_title=blueprint.role_title or blueprint.role_key.replace("_", " ").title(),
		section_title=section.title,
		count=len(slots),
		slot_lines=_slot_lines(slots, language),
		language_hint=_LANGUAGE_HINTS.get(language, language or "Python 3"),
	)
	started = time.monotonic()
	try:
		payload = first_json_object(generate(prompt, model))
	except Exception as exc:  # provider error or unparseable JSON: the bank fills in
		_LOGGER.warning("OA section %r generation failed: %s", section.key, exc)
		return []
	items = payload.get("questions") if isinstance(payload, Mapping) else None
	cleaned: list[dict[str, Any]] = []
	for index, item in enumerate(items or []):
		if not isinstance(item, Mapping):
			continue
		slot = slots[index] if index < len(slots) else None
		question = validate_generated(item, slot, section)
		if question is not None:
			cleaned.append(question)
	_LOGGER.info(
		"OA section %r: %d/%d usable from %s in %.1fs.", section.key, len(cleaned), len(slots), model, time.monotonic() - started
	)
	return cleaned


def _default_run(code: str, language: str) -> Mapping[str, Any]:
	from backend.dsa.code_executor import run_program

	return run_program(code, language)


def check_all(
	questions: Sequence[dict[str, Any]],
	run: Callable[[str, str], Mapping[str, Any]] | None,
) -> list[dict[str, Any]]:
	"""Run every answer check (code on Judge0 in parallel); drop rejected ones."""
	if not questions:
		return []
	with ThreadPoolExecutor(max_workers=4, thread_name_prefix="oa-verify") as pool:
		outcomes = list(pool.map(lambda q: verify_question(q, run), questions))
	kept: list[dict[str, Any]] = []
	for question, (status, corrected) in zip(questions, outcomes):
		if status == REJECTED:
			_LOGGER.info("OA question rejected by its answer check: %s", question["prompt"][:80])
			continue
		if corrected is not None and corrected != question["correct"]:
			if question["type"] == MCQ_MULTI:
				continue  # a run can only confirm one answer; multi keys stay as authored
			_LOGGER.info("OA answer key corrected by the check: %s", question["prompt"][:80])
			question = {**question, "correct": corrected}
		kept.append({**question, "verified": status})
	return kept


_CROSS_CHECK_PROMPT = """You are checking an assessment's answer key. Answer each multiple-choice question below yourself.
For select-all-that-apply questions give every correct option. If no option is correct, or the question is ambiguous or rests on a false premise, answer [].

{questions}

Return JSON only: {{"answers": [{{"q": 1, "correct": [0]}}]}} with 0-based option indexes."""

CROSS_CHECKED = "cross_checked"


def cross_check(
	questions: Sequence[dict[str, Any]],
	*,
	model: str,
	generate: Callable[[str, str], str],
) -> list[dict[str, Any]]:
	"""A second model answers the questions code can't check, without seeing
	the key. Disagreement, or "no option is right", drops the question.

	Caught in testing: a TLS question whose every option was wrong (a
	*.example.com certificate does match api.example.com), and a time-and-work
	answer of 15 days that is really 17.5.
	"""
	# Everything except code Judge0 actually ran: a numerical answer whose
	# formula agrees with its key is only self-consistent, not proven right
	# (seen: 57,600 five-digit multiples of 5 - it is 18,000).
	pending = [q for q in questions if not _ran_on_judge0(q)]
	if not pending:
		return list(questions)
	blocks = []
	for index, q in enumerate(pending, start=1):
		lines = [f"Q{index}. {q['prompt']}"]
		if q["code"]:
			lines.append(q["code"])
		lines.extend(f"  {i}) {option}" for i, option in enumerate(q["options"]))
		blocks.append("\n".join(lines))
	by_index: dict[int, list[int]] | None = None
	for attempt in range(2):
		try:
			raw = generate(_CROSS_CHECK_PROMPT.format(questions="\n\n".join(blocks)), model)
			answers = first_json_object(raw).get("answers") or []
			by_index = {int(a.get("q")): sorted({int(i) for i in (a.get("correct") or [])}) for a in answers if isinstance(a, Mapping)}
			break
		except Exception as exc:
			_LOGGER.warning("OA cross-check attempt %d failed: %s", attempt + 1, exc)
			time.sleep(2)
	if by_index is None:
		# No second opinion: unchecked questions are not used. In testing they
		# were exactly the ones with wrong keys; the curated bank fills in.
		return [q for q in questions if _ran_on_judge0(q)]
	agreed: dict[int, bool] = {}
	for index, q in enumerate(pending, start=1):
		agreed[id(q)] = by_index.get(index) == q["correct"]
		if not agreed[id(q)]:
			_LOGGER.info("OA question dropped by cross-check (%s vs %s): %s", by_index.get(index), q["correct"], q["prompt"][:80])
	result = []
	for q in questions:
		if _ran_on_judge0(q):
			result.append(q)
		elif agreed.get(id(q)):
			result.append({**q, "verified": VERIFIED if q.get("verified") == VERIFIED else CROSS_CHECKED})
	return result


def _ran_on_judge0(question: Mapping[str, Any]) -> bool:
	return question.get("verified") == VERIFIED and question.get("type") in {CODE_OUTPUT, PSEUDOCODE}


